-- Find the largest wordCount ≤ myWordCnt
function calcBudget(myLevel, myWordCnt, factor)
    factor = factor or 1.0
    local wordToPriceTable = levelMatrix[myLevel]

    if not wordToPriceTable then
        return "Unknown level"
    end

    local bestWordCount = nil

    for wc, _ in pairs(wordToPriceTable) do
        if wc <= myWordCnt then
            if bestWordCount == nil or wc > bestWordCount then
                bestWordCount = wc
            end
        end
    end

    local price = wordToPriceTable[bestWordCount]
    local result = (factor==1) and (" %.2f$"):format(price)
      or (" %.2f * %.1f = %.2f$"):format(price, factor, price*factor)
    return result
end


